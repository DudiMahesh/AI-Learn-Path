import React, { useState, useEffect } from 'react'
import { Brain, TrendingUp, Users, AlertTriangle, Sparkles, Info } from 'lucide-react'
import AIInsightCard from '../../components/insights/AIInsightCard'
import LoadingSpinner from '../../components/common/LoadingSpinner'
import EmptyState from '../../components/common/EmptyState'
import { dashboardService } from '../../services/dashboardService'

export default function AIInsightsPage() {
  const [data, setData] = useState(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    dashboardService.getDashboard()
      .then(d => setData(d))
      .catch(() => {})
      .finally(() => setLoading(false))
  }, [])

  if (loading) return <div className="flex justify-center items-center h-96"><LoadingSpinner /></div>

  if (!data?.diagnostic_completed) {
    return (
      <div className="max-w-5xl mx-auto py-8 px-4">
        <div className="flex items-center gap-3 mb-8">
          <Brain size={24} className="text-purple-600" />
          <h1 className="text-2xl font-bold text-gray-900">AI Insights</h1>
        </div>
        <EmptyState
          icon={Brain}
          title="No AI Insights Yet"
          message="Complete your diagnostic assessment to unlock ML-powered insights — your skill level prediction (Random Forest), learning profile (K-Means clustering), and personalized course matches (TF-IDF)."
        />
      </div>
    )
  }

  const prediction = data?.prediction || {}
  const profile = data?.learning_profile || {}
  const gaps = data?.skill_gaps || []
  const recs = data?.top_recommendations || []

  return (
    <div className="max-w-5xl mx-auto py-8 px-4">
      <div className="flex items-center gap-3 mb-2">
        <Brain size={24} className="text-purple-600" />
        <div>
          <h1 className="text-2xl font-bold text-gray-900">AI Insights</h1>
          <p className="text-sm text-gray-500">Machine Learning analysis of your learning profile.</p>
        </div>
      </div>

      {/* Explainability Banner */}
      <div className="bg-purple-50 border border-purple-100 rounded-2xl p-5 flex gap-3 my-6">
        <Info size={18} className="text-purple-600 flex-shrink-0 mt-0.5" />
        <p className="text-sm text-purple-700 leading-relaxed">
          These insights are generated by three ML models:
          <strong> Random Forest</strong> for skill level prediction,
          <strong> K-Means Clustering</strong> for learning profile identification, and
          <strong> TF-IDF + Cosine Similarity</strong> for course recommendations.
        </p>
      </div>

      <div className="space-y-8">
        {/* ML Model Outputs */}
        <section>
          <h2 className="font-semibold text-gray-700 mb-4 text-xs uppercase tracking-widest">Model Outputs</h2>
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">
            <AIInsightCard
              type="performance"
              title="Predicted Skill Level"
              value={prediction.level || 'Not yet predicted'}
              description={prediction.confidence ? `Confidence: ${Math.round(prediction.confidence * 100)}%` : 'Take assessment to generate prediction.'}
              badge="Random Forest"
            />
            <AIInsightCard
              type="profile"
              title="Learning Profile"
              value={profile.label || profile.cluster_label || 'Not yet clustered'}
              description={profile.description || profile.cluster_description || 'Your K-Means cluster will appear here after assessment.'}
              badge="K-Means Clustering"
            />
            <AIInsightCard
              type="recommendation"
              title="Matched Courses"
              value={`${recs.length} course${recs.length !== 1 ? 's' : ''}`}
              description="Ranked using TF-IDF cosine similarity against your skill gaps and career requirements."
              badge="TF-IDF"
            />
          </div>
        </section>

        {/* Skill Gap Analysis */}
        {gaps.length > 0 && (
          <section>
            <h2 className="font-semibold text-gray-700 mb-4 text-xs uppercase tracking-widest">Skill Gap Analysis</h2>
            <div className="bg-white rounded-2xl border border-gray-100 shadow-sm p-6">
              <div className="space-y-5">
                {gaps.map((gap, i) => (
                  <div key={i}>
                    <div className="flex items-center justify-between mb-1.5 flex-wrap gap-2">
                      <span className="text-sm font-semibold text-gray-800">{gap.skill}</span>
                      <div className="flex items-center gap-3 text-xs">
                        <span className="text-gray-400">Current: <strong className="text-gray-700">{Math.round(gap.current || 0)}%</strong></span>
                        <span className="text-gray-400">Required: <strong className="text-gray-700">{Math.round(gap.required || 0)}%</strong></span>
                        <span className={`font-semibold px-2 py-0.5 rounded-full ${
                          (gap.gap || 0) > 40 ? 'bg-red-100 text-red-700' :
                          (gap.gap || 0) > 20 ? 'bg-yellow-100 text-yellow-700' :
                          'bg-green-100 text-green-700'
                        }`}>Gap: {Math.round(gap.gap || 0)}</span>
                      </div>
                    </div>
                    <div className="relative w-full bg-gray-100 rounded-full h-2.5">
                      {/* Current level */}
                      <div className="h-2.5 rounded-full bg-blue-400 transition-all duration-700"
                        style={{ width: `${Math.min(gap.current || 0, 100)}%` }} />
                      {/* Required marker */}
                      <div className="absolute top-0 h-2.5 w-0.5 bg-gray-500 rounded-full"
                        style={{ left: `${Math.min(gap.required || 0, 100)}%` }} />
                    </div>
                    <div className="flex justify-between text-xs text-gray-400 mt-1">
                      <span>Current level</span>
                      <span>Target →</span>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </section>
        )}

        {/* Top Recommendations Preview */}
        {recs.length > 0 && (
          <section>
            <h2 className="font-semibold text-gray-700 mb-4 text-xs uppercase tracking-widest">Top Recommended Courses</h2>
            <div className="bg-white rounded-2xl border border-gray-100 shadow-sm divide-y divide-gray-50 overflow-hidden">
              {recs.slice(0, 5).map((rec, i) => (
                <div key={i} className="flex items-center gap-4 px-6 py-4">
                  <span className="w-7 h-7 rounded-lg bg-gradient-to-br from-blue-500 to-purple-600 flex items-center justify-center text-white text-xs font-bold flex-shrink-0">
                    {i + 1}
                  </span>
                  <div className="flex-1 min-w-0">
                    <p className="font-medium text-gray-800 text-sm truncate">{rec.title || `Recommendation #${i + 1}`}</p>
                    {rec.skill_gap_addressed && (
                      <p className="text-xs text-gray-400">Addresses: {rec.skill_gap_addressed}</p>
                    )}
                  </div>
                  {rec.recommendation_score && (
                    <span className="text-xs font-semibold text-blue-600 bg-blue-50 px-2.5 py-1 rounded-full flex-shrink-0">
                      {Math.round(rec.recommendation_score * 100)}% match
                    </span>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}
      </div>
    </div>
  )
}
